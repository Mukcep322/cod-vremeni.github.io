export type Story = {
  id: string;
  /** Подпись вкладки, если на остановке несколько историй */
  tab?: string;
  title: string;
  address: string;
  period: string;
  /** Координаты места [широта, долгота] */
  coords: [number, number];
  then: string;
  now: string;
  audio: string;
  /** Длительность аудио для подписи, например "1:20". Пусто — не показывать */
  audioDuration: string;
  /** Информация об объекте */
  text: string;
  /** Текст аудиолегенды. Пусто — блок не показывается */
  legend: string;
};

export type Task = {
  question: string;
  /** Точные правильные ответы. Сравнение без учёта регистра, пробелов, знаков и «ё/е» */
  answers: string[];
  /** Ответ засчитывается, если в нём есть все эти фрагменты (например, ["491", "13"]) */
  mustContain?: string[];
  /** Допуск для числового ответа: засчитывается |число − answers[0]| ≤ tolerance */
  tolerance?: number;
  /** Ответ числом: на телефоне открывается цифровая клавиатура */
  numeric?: boolean;
  hint: string;
  /** Текст на экране «Ответ принят» */
  reward: string;
};

export type Stop = {
  id: number;
  /** Название остановки в шторке «Следующая остановка» */
  title: string;
  /** Короткое имя для подписи на схеме */
  short: string;
  stories: Story[];
  task: Task;
  source: { label: string; url: string };
};

